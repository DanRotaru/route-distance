export function TurnIcon({ step }: { step: Step }) {
  if (step.type === 'depart') return <Icon name="tripOrigin" size={20} />;
  if (step.type === 'arrive') return <Icon name="place" size={20} className="ic-dest" />;
  if (step.type.includes('roundabout') || step.type.includes('rotary')) return <Icon name="roundabout" size={20} />;
  const angle = TURN_ANGLE[step.modifier ?? 'straight'] ?? 0;
  return <Icon name="arrow" size={20} style={{ transform: `rotate(${angle}deg)` }} />;
}

